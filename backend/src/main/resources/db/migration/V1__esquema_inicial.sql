-- Esquema inicial de Repostea (Flyway). Se irá ampliando con nuevas versiones V2, V3...
CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    nombre VARCHAR(255),
    rol VARCHAR(20),
    telegram_chat_id VARCHAR(255),
    fecha_alta TIMESTAMP
);

CREATE TABLE vehiculo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255),
    combustible VARCHAR(20),
    consumo_l100km DOUBLE PRECISION NOT NULL,
    capacidad_deposito INTEGER NOT NULL,
    usuario_id BIGINT NOT NULL REFERENCES usuario(id)
);

CREATE TABLE gasolinera (
    id BIGINT PRIMARY KEY,
    rotulo VARCHAR(255),
    direccion VARCHAR(255),
    municipio VARCHAR(255),
    provincia VARCHAR(255),
    latitud DOUBLE PRECISION NOT NULL,
    longitud DOUBLE PRECISION NOT NULL,
    horario VARCHAR(255)
);

CREATE TABLE precio (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gasolinera_id BIGINT NOT NULL REFERENCES gasolinera(id),
    combustible VARCHAR(20),
    importe NUMERIC(5,3),
    desde TIMESTAMP
);
CREATE INDEX idx_precio_gasolinera ON precio(gasolinera_id, combustible, desde);

CREATE TABLE precio_luz (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE,
    hora INTEGER NOT NULL,
    precio_kwh NUMERIC(6,5)
);

CREATE TABLE alerta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dtype VARCHAR(31) NOT NULL,
    usuario_id BIGINT NOT NULL REFERENCES usuario(id),
    activa BOOLEAN NOT NULL,
    canal VARCHAR(20),
    ultimo_aviso TIMESTAMP,
    gasolinera_id BIGINT REFERENCES gasolinera(id),
    combustible VARCHAR(20),
    precio_limite NUMERIC(38,2),
    precio_max_kwh NUMERIC(38,2)
);

CREATE TABLE carga_datos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fuente VARCHAR(20),
    inicio TIMESTAMP,
    fin TIMESTAMP,
    estado VARCHAR(20),
    registros INTEGER NOT NULL,
    error VARCHAR(255)
);
